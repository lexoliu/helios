/// Defines [`MountedFs`] over the closed set of filesystem kinds, with a
/// [`FileSystem`] implementation that forwards each operation to the kind
/// it holds. Adding a kind is one line here.
macro_rules! mount_kinds {
    ($($(#[$doc:meta])* $kind:ident($fs:ty)),+ $(,)?) => {
        /// A mounted filesystem of one of the kinds the kernel builds.
        #[derive(Clone)]
        pub enum MountedFs<H> {
            $($(#[$doc])* $kind($fs),)+
        }

        impl<H: HostFileSystem> FileSystem for MountedFs<H> {
            type Payer = StoragePayer;

            async fn stat(&self, path: FsPath<'_>) -> FsResult<Metadata> {
                match self { $(Self::$kind(fs) => fs.stat(path).await,)+ }
            }

            async fn open(
                &self,
                path: FsPath<'_>,
                flags: OpenFlags,
                now: u64,
                payer: &StoragePayer,
            ) -> FsResult<Metadata> {
                match self { $(Self::$kind(fs) => fs.open(path, flags, now, payer).await,)+ }
            }

            async fn read_at(
                &self,
                path: FsPath<'_>,
                offset: u64,
                max_bytes: usize,
            ) -> FsResult<Bytes> {
                match self { $(Self::$kind(fs) => fs.read_at(path, offset, max_bytes).await,)+ }
            }

            fn write_with<'a, F>(
                &'a self,
                path: FsPath<'a>,
                position: WritePosition,
                len: usize,
                now: u64,
                payer: &'a StoragePayer,
                fill: F,
            ) -> impl Future<Output = FsResult<u64>> + Send + 'a
            where
                F: FnMut(&mut [u8]),
            {
                // Each kind runs `fill` in this call, so the dispatch must
                // too: the arms' futures are carried in one enum rather
                // than awaited in an async body that would hold `fill`.
                match self {
                    $(Self::$kind(fs) => MountedWrite::$kind {
                        future: fs.write_with(path, position, len, now, payer, fill),
                    },)+
                }
            }

            async fn set_size(
                &self,
                path: FsPath<'_>,
                size: u64,
                now: u64,
                payer: &StoragePayer,
            ) -> FsResult<()> {
                match self { $(Self::$kind(fs) => fs.set_size(path, size, now, payer).await,)+ }
            }

            async fn set_times(
                &self,
                path: FsPath<'_>,
                access_nanos: Option<u64>,
                modified_nanos: Option<u64>,
                now: u64,
                payer: &StoragePayer,
            ) -> FsResult<()> {
                match self {
                    $(Self::$kind(fs) => {
                        fs.set_times(path, access_nanos, modified_nanos, now, payer)
                            .await
                    })+
                }
            }

            async fn read_dir(
                &self,
                path: FsPath<'_>,
                cookie: DirCookie,
                max_entries: usize,
            ) -> FsResult<Vec<DirEntry>> {
                match self { $(Self::$kind(fs) => fs.read_dir(path, cookie, max_entries).await,)+ }
            }

            async fn create_directory(
                &self,
                path: FsPath<'_>,
                now: u64,
                payer: &StoragePayer,
            ) -> FsResult<()> {
                match self { $(Self::$kind(fs) => fs.create_directory(path, now, payer).await,)+ }
            }

            async fn remove_directory(&self, path: FsPath<'_>, payer: &StoragePayer) -> FsResult<()> {
                match self { $(Self::$kind(fs) => fs.remove_directory(path, payer).await,)+ }
            }

            async fn unlink(&self, path: FsPath<'_>, payer: &StoragePayer) -> FsResult<()> {
                match self { $(Self::$kind(fs) => fs.unlink(path, payer).await,)+ }
            }

            async fn rename(
                &self,
                source: FsPath<'_>,
                destination: FsPath<'_>,
                now: u64,
                payer: &StoragePayer,
            ) -> FsResult<()> {
                match self {
                    $(Self::$kind(fs) => fs.rename(source, destination, now, payer).await,)+
                }
            }

            async fn link(
                &self,
                existing: FsPath<'_>,
                link: FsPath<'_>,
                now: u64,
                payer: &StoragePayer,
            ) -> FsResult<()> {
                match self { $(Self::$kind(fs) => fs.link(existing, link, now, payer).await,)+ }
            }

            async fn symlink(
                &self,
                target: &str,
                link: FsPath<'_>,
                now: u64,
                payer: &StoragePayer,
            ) -> FsResult<()> {
                match self { $(Self::$kind(fs) => fs.symlink(target, link, now, payer).await,)+ }
            }

            async fn read_link(&self, path: FsPath<'_>) -> FsResult<String> {
                match self { $(Self::$kind(fs) => fs.read_link(path).await,)+ }
            }

            async fn sync(&self, path: FsPath<'_>) -> FsResult<()> {
                match self { $(Self::$kind(fs) => fs.sync(path).await,)+ }
            }

            async fn sync_data(&self, path: FsPath<'_>) -> FsResult<()> {
                match self { $(Self::$kind(fs) => fs.sync_data(path).await,)+ }
            }
        }

        pin_project_lite::pin_project! {
            /// The write future of whichever kind a [`MountedFs`] holds.
            #[project = MountedWriteProjection]
            enum MountedWrite<$($kind),+> {
                $($kind { #[pin] future: $kind },)+
            }
        }

        impl<$($kind: Future<Output = FsResult<u64>>),+> Future for MountedWrite<$($kind),+> {
            type Output = FsResult<u64>;

            fn poll(self: Pin<&mut Self>, cx: &mut Context<'_>) -> Poll<Self::Output> {
                match self.project() {
                    $(MountedWriteProjection::$kind { future } => future.poll(cx),)+
                }
            }
        }
    };
}

/// Writes `data` at `position` through [`FileSystem::write_with`], and
/// resolves with the offset it landed at: the filesystem tests' write.
#[cfg(test)]
pub(crate) async fn write_bytes<F: FileSystem>(
    fs: &F,
    path: FsPath<'_>,
    position: WritePosition,
    data: &[u8],
    now: u64,
    payer: &F::Payer,
) -> FsResult<u64> {
    let mut written = 0;
    fs.write_with(path, position, data.len(), now, payer, |run| {
        run.copy_from_slice(&data[written..written + run.len()]);
        written += run.len();
    })
    .await
}

