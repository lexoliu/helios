/// Mounts one table holds besides its root.
///
/// The bound is kernel memory, not guest data: a slot is a few words and a
/// cache line of pin count, and a machine with a dozen disks mounted is
/// already more than the platform attaches.
pub const MAX_MOUNTS: usize = 16;

/// Device id of the boot image.
pub const BOOT_DEVICE: DeviceId = DeviceId::new(AuthorityDomain::GUEST_BOOTFS.raw());

/// Device id of every namespace's root layer. Two namespaces never see
/// each other's layer, so they share the number the way two containers'
/// root filesystems may.
pub const ROOT_LAYER_DEVICE: DeviceId = DeviceId::new(AuthorityDomain::GUEST_ROOT_LAYER.raw());

/// The deepest chain of symbolic links one resolution follows.
pub const MAX_SYMLINK_DEPTH: usize = 16;

/// Defines [`MountedFs`] over the closed set of filesystem kinds, with a
/// [`FileSystem`] implementation that forwards each operation to the kind
/// it holds. Adding a kind is one line here.
macro_rules! mount_kinds {
    ($($(#[$doc:meta])* $kind:ident($fs:ty)),+ $(,)?) => {
        /// A mounted filesystem of one of the kinds the kernel builds.
        #[derive(Clone)]
        pub enum MountedFs<H> {
            $($(#[$doc])* $kind($fs),)+
        }

        impl<H: HostFileSystem> FileSystem for MountedFs<H> {
            async fn stat(&self, path: FsPath<'_>) -> FsResult<Metadata> {
                match self { $(Self::$kind(fs) => fs.stat(path).await,)+ }
            }

            async fn open(&self, path: FsPath<'_>, flags: OpenFlags, now: u64) -> FsResult<Metadata> {
                match self { $(Self::$kind(fs) => fs.open(path, flags, now).await,)+ }
            }

            async fn read_at(
                &self,
                path: FsPath<'_>,
                offset: u64,
                max_bytes: usize,
            ) -> FsResult<Bytes> {
                match self { $(Self::$kind(fs) => fs.read_at(path, offset, max_bytes).await,)+ }
            }

            async fn write_at(
                &self,
                path: FsPath<'_>,
                offset: u64,
                data: &[u8],
                now: u64,
            ) -> FsResult<()> {
                match self { $(Self::$kind(fs) => fs.write_at(path, offset, data, now).await,)+ }
            }

            async fn append(&self, path: FsPath<'_>, data: &[u8], now: u64) -> FsResult<u64> {
                match self { $(Self::$kind(fs) => fs.append(path, data, now).await,)+ }
            }

            async fn set_size(&self, path: FsPath<'_>, size: u64, now: u64) -> FsResult<()> {
                match self { $(Self::$kind(fs) => fs.set_size(path, size, now).await,)+ }
            }

            async fn set_times(
                &self,
                path: FsPath<'_>,
                access_nanos: Option<u64>,
                modified_nanos: Option<u64>,
                now: u64,
            ) -> FsResult<()> {
                match self {
                    $(Self::$kind(fs) => {
                        fs.set_times(path, access_nanos, modified_nanos, now).await
                    })+
                }
            }

            async fn read_dir(
                &self,
                path: FsPath<'_>,
                cookie: DirCookie,
                max_entries: usize,
            ) -> FsResult<Vec<DirEntry>> {
                match self { $(Self::$kind(fs) => fs.read_dir(path, cookie, max_entries).await,)+ }
            }

            async fn create_directory(&self, path: FsPath<'_>, now: u64) -> FsResult<()> {
                match self { $(Self::$kind(fs) => fs.create_directory(path, now).await,)+ }
            }

            async fn remove_directory(&self, path: FsPath<'_>) -> FsResult<()> {
                match self { $(Self::$kind(fs) => fs.remove_directory(path).await,)+ }
            }

            async fn unlink(&self, path: FsPath<'_>) -> FsResult<()> {
                match self { $(Self::$kind(fs) => fs.unlink(path).await,)+ }
            }

            async fn rename(
                &self,
                source: FsPath<'_>,
                destination: FsPath<'_>,
                now: u64,
            ) -> FsResult<()> {
                match self { $(Self::$kind(fs) => fs.rename(source, destination, now).await,)+ }
            }

            async fn link(&self, existing: FsPath<'_>, link: FsPath<'_>, now: u64) -> FsResult<()> {
                match self { $(Self::$kind(fs) => fs.link(existing, link, now).await,)+ }
            }

            async fn symlink(&self, target: &str, link: FsPath<'_>, now: u64) -> FsResult<()> {
                match self { $(Self::$kind(fs) => fs.symlink(target, link, now).await,)+ }
            }

            async fn read_link(&self, path: FsPath<'_>) -> FsResult<String> {
                match self { $(Self::$kind(fs) => fs.read_link(path).await,)+ }
            }

            async fn sync(&self, path: FsPath<'_>) -> FsResult<()> {
                match self { $(Self::$kind(fs) => fs.sync(path).await,)+ }
            }

            async fn sync_data(&self, path: FsPath<'_>) -> FsResult<()> {
                match self { $(Self::$kind(fs) => fs.sync_data(path).await,)+ }
            }
        }
    };
}

mount_kinds! {
    /// A namespace's root: its own tree over the boot image. Only the
    /// table's root is of this kind; [`MountTable::mount`] refuses it.
    Root(RootFs),
    /// The boot image on its own, read-only.
    Boot(BootFs),
    /// A tree in kernel memory, shared by every namespace that sees it.
    Memory(MemoryFs),
    /// The host share over 9p.
    Host(HostShare<H>),
}

/// Why a mount or unmount was refused.
#[derive(Clone, Debug, Error, PartialEq, Eq)]
pub enum MountError {
    #[error("mount point {0:?} is not a normalized absolute path below /")]
    InvalidPoint(String),
    #[error("{0:?} is already a mount point")]
    AlreadyMounted(String),
    #[error("{0:?} is not a mount point")]
    NotMounted(String),
    #[error("{0:?} has mounts below it")]
    Busy(String),
    #[error("the mount table holds {MAX_MOUNTS} mounts already")]
    TableFull,
    #[error("the root mount is the kernel's and cannot be mounted again")]
    RootKind,
    #[error("mount point {point:?} cannot be used: {error}")]
    Filesystem { point: String, error: FsError },
}

const SLOT_EMPTY: u8 = 0;
const SLOT_LIVE: u8 = 1;
const SLOT_RETIRING: u8 = 2;

struct Mount<H> {
    point: String,
    rights: FileSystemRights,
    fs: MountedFs<H>,
}

/// One mount's place in the table.
///
/// `mount` is written only by the writer, only while `state` is
/// [`SLOT_EMPTY`] or [`SLOT_RETIRING`] with `pins` at zero, and read only
/// by a resolution that pinned the slot and then saw [`SLOT_LIVE`].
struct Slot<H> {
    /// Resolutions currently looking at this slot. Written by every
    /// resolving processor.
    pins: CachePadded<AtomicUsize>,
    state: AtomicU8,
    mount: UnsafeCell<Option<Mount<H>>>,
}

// SAFETY: `mount` is shared across processors under the protocol on
// `Slot`: the writer touches it only when no resolution can be reading it
// (empty, or retiring with no pins), and a resolution reads it only after
// pinning the slot and observing it live, which the writer's sequentially
// consistent publication orders after the write.
unsafe impl<H: Send + Sync> Sync for Slot<H> {}

impl<H> Slot<H> {
    fn new() -> Self {
        Self {
            pins: CachePadded::new(AtomicUsize::new(0)),
            state: AtomicU8::new(SLOT_EMPTY),
            mount: UnsafeCell::new(None),
        }
    }

    /// Runs `read` on the mount when the slot is live, with the slot
    /// pinned for the duration.
    fn read<R>(&self, read: impl FnOnce(&Mount<H>) -> R) -> Option<R> {
        if self.state.load(AtomicOrdering::Acquire) != SLOT_LIVE {
            return None;
        }
        self.pins.fetch_add(1, AtomicOrdering::SeqCst);
        let result = if self.state.load(AtomicOrdering::SeqCst) == SLOT_LIVE {
            // SAFETY: the slot is pinned and live, so the writer has
            // published the mount and will not touch it until this pin is
            // released (see `Slot`).
            let mount = unsafe { &*self.mount.get() };
            Some(read(mount.as_ref().expect("a live slot holds a mount")))
        } else {
            None
        };
        self.pins.fetch_sub(1, AtomicOrdering::Release);
        result
    }
}

struct TableInner<H> {
    boot: BootFs,
    slots: [Slot<H>; MAX_MOUNTS],
    writer: spin::Mutex<()>,
    next_device: AtomicU64,
}

/// The kernel's mount table. Clones share it.
pub struct MountTable<H> {
    inner: Arc<TableInner<H>>,
}

impl<H> Clone for MountTable<H> {
    fn clone(&self) -> Self {
        Self {
            inner: self.inner.clone(),
        }
    }
}

/// Whether `absolute` is `point` or lies below it.
fn point_covers(point: &str, absolute: &str) -> bool {
    absolute
        .strip_prefix(point)
        .is_some_and(|rest| rest.is_empty() || rest.starts_with('/'))
}

/// A mount point: a normalized absolute path other than `/`.
fn valid_point(point: &str) -> bool {
    point.len() > 1 && point.strip_prefix('/').and_then(FsPath::new).is_some()
}

impl<H: Clone> MountTable<H> {
    /// A table whose root mount is `boot` under each namespace's own
    /// layer, with nothing else mounted.
    pub fn new(boot: BootFs) -> Self {
        Self {
            inner: Arc::new(TableInner {
                boot,
                slots: core::array::from_fn(|_| Slot::new()),
                writer: spin::Mutex::new(()),
                next_device: AtomicU64::new(AuthorityDomain::FIRST_MOUNTED.raw()),
            }),
        }
    }

    /// The boot image under every namespace's root.
    pub fn boot(&self) -> &BootFs {
        &self.inner.boot
    }

    /// A device id no other filesystem in this table has, for a tree the
    /// table is about to mount.
    pub fn allocate_device(&self) -> DeviceId {
        DeviceId::new(self.inner.next_device.fetch_add(1, AtomicOrdering::Relaxed))
    }

    /// Mounts `fs` at `point`.
    ///
    /// Checks only the table: the namespace that asks checks the point
    /// against the filesystem beneath it first (see [`Namespace::mount`]).
    pub fn mount(
        &self,
        point: &str,
        fs: MountedFs<H>,
        rights: FileSystemRights,
    ) -> Result<(), MountError> {
        if !valid_point(point) {
            return Err(MountError::InvalidPoint(point.to_owned()));
        }
        if matches!(fs, MountedFs::Root(_)) {
            return Err(MountError::RootKind);
        }
        let _writer = self.inner.writer.lock();
        let mut empty = None;
        for slot in &self.inner.slots {
            match slot.state.load(AtomicOrdering::Acquire) {
                SLOT_EMPTY => {
                    empty.get_or_insert(slot);
                }
                _ => {
                    // SAFETY: the writer lock is held, so no other writer
                    // is changing this slot, and a live or retiring slot's
                    // mount stays in place until a writer clears it.
                    let mounted = unsafe { &*slot.mount.get() };
                    if mounted.as_ref().is_some_and(|mount| mount.point == point) {
                        return Err(MountError::AlreadyMounted(point.to_owned()));
                    }
                }
            }
        }
        let slot = empty.ok_or(MountError::TableFull)?;
        // SAFETY: the slot is empty and the writer lock is held: no
        // resolution reads an empty slot's mount and no writer races.
        unsafe {
            *slot.mount.get() = Some(Mount {
                point: point.to_owned(),
                rights,
                fs,
            });
        }
        slot.state.store(SLOT_LIVE, AtomicOrdering::SeqCst);
        Ok(())
    }

    /// Unmounts the filesystem at `point`, once no resolution is looking
    /// at it.
    pub async fn unmount(&self, point: &str) -> Result<(), MountError> {
        let slot = {
            let _writer = self.inner.writer.lock();
            let mut found = None;
            for slot in &self.inner.slots {
                if slot.state.load(AtomicOrdering::Acquire) != SLOT_LIVE {
                    continue;
                }
                // SAFETY: as in `mount`, the writer lock is held.
                let mounted = unsafe { &*slot.mount.get() }
                    .as_ref()
                    .expect("a live slot holds a mount");
                if mounted.point == point {
                    found = Some(slot);
                } else if point_covers(point, &mounted.point) {
                    return Err(MountError::Busy(point.to_owned()));
                }
            }
            let slot = found.ok_or_else(|| MountError::NotMounted(point.to_owned()))?;
            slot.state.store(SLOT_RETIRING, AtomicOrdering::SeqCst);
            slot
        };
        while slot.pins.load(AtomicOrdering::SeqCst) != 0 {
            crate::yield_now().await;
        }
        let retired = {
            let _writer = self.inner.writer.lock();
            // SAFETY: the slot is retiring with no pins and the writer lock
            // is held; every resolution that pins it from here on sees it
            // retiring and leaves the mount alone.
            let retired = unsafe { (*slot.mount.get()).take() };
            slot.state.store(SLOT_EMPTY, AtomicOrdering::Release);
            retired
        };
        drop(retired);
        Ok(())
    }

    /// The mount whose point is the longest prefix of `absolute`, as the
    /// length of its point, its rights and its filesystem.
    fn longest_match(&self, absolute: &str) -> Option<(usize, FileSystemRights, MountedFs<H>)> {
        let mut best: Option<(usize, FileSystemRights, MountedFs<H>)> = None;
        for slot in &self.inner.slots {
            let longer = |len: usize| best.as_ref().is_none_or(|(best, _, _)| len > *best);
            if let Some(found) = slot.read(|mount| {
                (point_covers(&mount.point, absolute) && longer(mount.point.len()))
                    .then(|| (mount.point.len(), mount.rights, mount.fs.clone()))
            }) {
                best = found.or(best);
            }
        }
        best
    }

    /// Names of the mount points directly inside the directory
    /// `directory`.
    fn points_inside(&self, directory: &str) -> Vec<String> {
        let mut names = Vec::new();
        for slot in &self.inner.slots {
            if let Some(Some(name)) = slot.read(|mount| {
                let (parent, name) = mount.point.rsplit_once('/')?;
                let parent = if parent.is_empty() { "/" } else { parent };
                (parent == directory).then(|| String::from(name))
            }) {
                names.push(name);
            }
        }
        names
    }
}

/// A guest path resolved to the mount that owns it.
#[derive(Clone)]
pub struct Resolved<H> {
    fs: MountedFs<H>,
    rights: FileSystemRights,
    absolute: String,
    /// Length of the mount point in `absolute`; `0` for the root mount.
    point_len: usize,
}

impl<H: HostFileSystem> Resolved<H> {
    /// The filesystem, for reading.
    pub fn fs(&self) -> &MountedFs<H> {
        &self.fs
    }

    /// The filesystem, for changing: refused when the mount is read-only.
    pub fn writable(&self) -> FsResult<&MountedFs<H>> {
        if self.rights.contains(FileSystemRights::WRITE) {
            Ok(&self.fs)
        } else {
            Err(FsError::ReadOnly)
        }
    }

    /// The path inside the mount's filesystem.
    pub fn path(&self) -> FsPath<'_> {
        let inside = &self.absolute[self.point_len..];
        FsPath::new(inside.strip_prefix('/').unwrap_or(inside))
            .expect("a resolved path is normalized")
    }

    /// The guest path this was resolved from.
    pub fn absolute(&self) -> &str {
        &self.absolute
    }

    /// The guest path of the mount's root.
    pub fn mount_point(&self) -> &str {
        if self.point_len == 0 {
            "/"
        } else {
            &self.absolute[..self.point_len]
        }
    }

    /// Whether `other` lies on the same mount, so a rename or link between
    /// the two can stay within one filesystem.
    pub fn same_mount(&self, other: &Self) -> bool {
        self.mount_point() == other.mount_point()
    }

    /// Whether the path names the root of its mount.
    pub fn is_mount_root(&self) -> bool {
        self.path().is_root()
    }

    /// The whole of the regular file at this path, with the provenance of
    /// the layer that produced the bytes.
    pub async fn read_whole(&self) -> FsResult<FileContents> {
        let path = self.path();
        match &self.fs {
            MountedFs::Root(root) => root.read_whole(path).await,
            MountedFs::Boot(boot) => boot.file_contents(path).map(FileContents::Boot),
            MountedFs::Memory(fs) => read_all(fs, path).await.map(FileContents::Written),
            MountedFs::Host(fs) => read_all(fs, path).await.map(FileContents::Written),
        }
    }
}

/// A file's whole contents, typed by the layer that produced them.
///
/// Provenance is decided by which filesystem returned the bytes, in the
/// same call that returned them, never by a path or a separate check a
/// concurrent change could invalidate. Only the boot image constructs
/// [`FileContents::Boot`]; every other layer (a namespace's own tree, a
/// tree in kernel memory, a host share, bytes copied up from the boot
/// image) yields [`FileContents::Written`].
#[derive(Clone, Debug)]
pub enum FileContents {
    /// Bytes exactly as the boot payload supplied them.
    Boot(BootfsBytes),
    /// Bytes any other filesystem holds.
    Written(Bytes),
}

/// The whole of the regular file at `path` on `fs`.
pub(crate) async fn read_all<F: FileSystem>(fs: &F, path: FsPath<'_>) -> FsResult<Bytes> {
    let metadata = fs.stat(path).await?;
    match metadata.kind {
        NodeKind::File => {}
        NodeKind::Directory => return Err(FsError::IsDirectory),
        NodeKind::Symlink => return Err(FsError::Invalid),
    }
    let size = usize::try_from(metadata.size).map_err(|_| FsError::Overflow)?;
    let first = fs.read_at(path, 0, size).await?;
    if first.len() == size {
        return Ok(first);
    }
    // A filesystem may answer in pieces (9p bounds one read by its
    // message size): gather the rest.
    let mut gathered = BytesMut::with_capacity(size);
    gathered.extend_from_slice(&first);
    loop {
        let chunk = fs
            .read_at(path, gathered.len() as u64, size - gathered.len())
            .await?;
        if chunk.is_empty() {
            break;
        }
        gathered.extend_from_slice(&chunk);
    }
    Ok(gathered.freeze())
}

/// The kernel's identity for a filesystem object.
pub fn object_identity(metadata: &Metadata) -> ObjectIdentity {
    ObjectIdentity::new(
        AuthorityDomain::new(metadata.id.device.raw()),
        metadata.id.inode,
    )
}

/// One process tree's view of the filesystem: the kernel's table and the
/// tree's own root layer. Clones share both.
pub struct Namespace<H> {
    table: MountTable<H>,
    root: RootFs,
}

impl<H> Clone for Namespace<H> {
    fn clone(&self) -> Self {
        Self {
            table: self.table.clone(),
            root: self.root.clone(),
        }
    }
}

impl<H: HostFileSystem> Namespace<H> {
    /// A namespace with a fresh, empty root layer.
    pub fn new(table: MountTable<H>) -> Self {
        Self::sharing(table, MemoryFs::new(ROOT_LAYER_DEVICE))
    }

    /// A namespace whose root layer is `layer`, shared with whoever else
    /// holds it (the process tree that spawned this one).
    pub fn sharing(table: MountTable<H>, layer: MemoryFs) -> Self {
        let root = RootFs::new(layer, table.boot().clone());
        Self { table, root }
    }

    /// The writable layer of this namespace's root, for a child to share.
    pub fn root_layer(&self) -> MemoryFs {
        self.root.upper().clone()
    }

    /// Takes `layer` as this namespace's root layer: a child that ran to
    /// completion hands its tree's root back to the parent it rejoins.
    pub fn adopt_root_layer(&mut self, layer: MemoryFs) {
        self.root = RootFs::new(layer, self.table.boot().clone());
    }

    pub fn table(&self) -> &MountTable<H> {
        &self.table
    }

    /// Resolves a normalized absolute guest path (as
    /// [`crate::resolve_child_path`] produces) to the mount that owns it.
    pub fn resolve(&self, absolute: &str) -> FsResult<Resolved<H>> {
        if !absolute.starts_with('/') {
            return Err(FsError::Invalid);
        }
        let (point_len, rights, fs) = self.table.longest_match(absolute).unwrap_or((
            0,
            FileSystemRights::READ | FileSystemRights::WRITE,
            MountedFs::Root(self.root.clone()),
        ));
        let resolved = Resolved {
            fs,
            rights,
            absolute: absolute.to_owned(),
            point_len,
        };
        let inside = &resolved.absolute[point_len..];
        FsPath::new(inside.strip_prefix('/').unwrap_or(inside)).ok_or(FsError::Invalid)?;
        Ok(resolved)
    }

    /// Resolves `absolute`, following a final symbolic link as `follow`
    /// says, through as many mounts as the links lead to.
    ///
    /// A followed resolution starts inside its floor and never leaves it:
    /// a link that leads out, a link placed at the floor itself included,
    /// is refused with [`FsError::NotPermitted`].
    pub async fn resolve_following(
        &self,
        absolute: &str,
        follow: Follow<'_>,
    ) -> FsResult<Resolved<H>> {
        let mut resolved = self.resolve(absolute)?;
        let Follow::Within(floor) = follow else {
            return Ok(resolved);
        };
        if !within_directory(floor, absolute) {
            return Err(FsError::NotPermitted);
        }
        for _ in 0..MAX_SYMLINK_DEPTH {
            match resolved.fs().stat(resolved.path()).await {
                Ok(metadata) if metadata.kind == NodeKind::Symlink => {}
                // Absent, or not a link: the path names itself.
                Ok(_) | Err(FsError::NoEntry) => return Ok(resolved),
                Err(error) => return Err(error),
            }
            let target = resolved.fs().read_link(resolved.path()).await?;
            let followed = symlink_target(resolved.absolute(), &target)?;
            if !within_directory(floor, &followed) {
                return Err(FsError::NotPermitted);
            }
            resolved = self.resolve(&followed)?;
        }
        Err(FsError::Loop)
    }

    /// Describes `absolute`, following a final symbolic link as `follow`
    /// says.
    pub async fn stat(&self, absolute: &str, follow: Follow<'_>) -> FsResult<Metadata> {
        let resolved = self.resolve_following(absolute, follow).await?;
        resolved.fs().stat(resolved.path()).await
    }

    /// Every entry of the directory at `absolute`, with the mount points
    /// directly inside it, which the filesystem beneath may not have.
    pub async fn list(&self, absolute: &str) -> FsResult<Vec<DirEntry>> {
        /// Entries one listing request asks for.
        const BATCH: usize = 256;
        let resolved = self.resolve(absolute)?;
        let mut entries: Vec<DirEntry> = Vec::new();
        let mut cookie = DirCookie::START;
        loop {
            let batch = resolved
                .fs()
                .read_dir(resolved.path(), cookie, BATCH)
                .await?;
            let complete = batch.len() < BATCH;
            if let Some(last) = batch.last() {
                cookie = last.next;
            }
            entries.extend(batch);
            if complete {
                break;
            }
        }
        for name in self.table.points_inside(absolute) {
            if !entries.iter().any(|entry| entry.name == name) {
                entries.push(DirEntry {
                    name,
                    kind: NodeKind::Directory,
                    inode: 0,
                    next: DirCookie::START,
                });
            }
        }
        Ok(entries)
    }

    /// Renames within one mount; across two, [`FsError::CrossDevice`].
    pub async fn rename(&self, source: &str, destination: &str, now: u64) -> FsResult<()> {
        let source = self.resolve(source)?;
        let destination = self.resolve(destination)?;
        if !source.same_mount(&destination) {
            return Err(FsError::CrossDevice);
        }
        if source.is_mount_root() || destination.is_mount_root() {
            return Err(FsError::NotPermitted);
        }
        source
            .writable()?
            .rename(source.path(), destination.path(), now)
            .await
    }

    /// Links within one mount; across two, [`FsError::CrossDevice`].
    pub async fn link(&self, existing: &str, link: &str, now: u64) -> FsResult<()> {
        let existing = self.resolve(existing)?;
        let link = self.resolve(link)?;
        if !existing.same_mount(&link) {
            return Err(FsError::CrossDevice);
        }
        if existing.is_mount_root() || link.is_mount_root() {
            return Err(FsError::NotPermitted);
        }
        existing
            .writable()?
            .link(existing.path(), link.path(), now)
            .await
    }

    /// Mounts `fs` at the point `cap` names, after checking the point
    /// against what lies beneath it: its parent must be a directory, and
    /// the point itself a directory or nothing.
    pub async fn mount(
        &self,
        cap: &MountCap,
        fs: MountedFs<H>,
        rights: FileSystemRights,
    ) -> Result<(), MountError> {
        let point = cap.point();
        if !valid_point(point) {
            return Err(MountError::InvalidPoint(point.to_owned()));
        }
        let refuse = |error| MountError::Filesystem {
            point: point.to_owned(),
            error,
        };
        let parent = crate::parent_path(point);
        // The cap is the authority over where a mount goes, so the parent's
        // links are followed anywhere in the namespace.
        match self
            .stat(parent, Follow::Within("/"))
            .await
            .map_err(refuse)?
            .kind
        {
            NodeKind::Directory => {}
            NodeKind::File | NodeKind::Symlink => return Err(refuse(FsError::NotDirectory)),
        }
        match self.stat(point, Follow::No).await {
            Ok(metadata) if metadata.kind != NodeKind::Directory => {
                return Err(refuse(FsError::NotDirectory));
            }
            Ok(_) | Err(FsError::NoEntry) => {}
            Err(error) => return Err(refuse(error)),
        }
        self.table.mount(point, fs, rights)
    }

    /// Unmounts the filesystem at the point `cap` names, once no
    /// resolution is looking at it.
    pub async fn unmount(&self, cap: &UnmountCap) -> Result<(), MountError> {
        self.table.unmount(cap.point()).await
    }
}

/// Whether a resolution follows a final symbolic link.
#[derive(Clone, Copy, Debug)]
pub enum Follow<'a> {
    /// The path names the link itself.
    No,
    /// The path names what the link leads to, which must lie inside the
    /// directory given: the descriptor or grant the path was resolved
    /// against.
    Within(&'a str),
}

/// Whether `path` is the directory `directory` or lies below it.
pub fn within_directory(directory: &str, path: &str) -> bool {
    directory == "/" && path.starts_with('/') || point_covers(directory, path)
}

/// The guest path a symbolic link at `link` with target text `target`
/// names.
///
/// Targets stay inside the directory that holds the link: an absolute
/// target or one that climbs with `..` is refused, as the guest
/// filesystem has always refused them.
pub fn symlink_target(link: &str, target: &str) -> FsResult<String> {
    if target.is_empty() || target.starts_with('/') {
        return Err(FsError::NotPermitted);
    }
    if target.split('/').any(|segment| segment == "..") {
        return Err(FsError::NotPermitted);
    }
    crate::resolve_child_path(crate::parent_path(link), target).map_err(|_| FsError::NotPermitted)
}

/// `directory/name` as a filesystem-relative path.
pub(crate) fn join_fs_path(directory: FsPath<'_>, name: &str) -> String {
    if directory.is_root() {
        return name.to_owned();
    }
    let mut joined = String::with_capacity(directory.as_str().len() + 1 + name.len());
    joined.push_str(directory.as_str());
    joined.push('/');
    joined.push_str(name);
    joined
}

/// Orders `path` against the run of paths that start with `directory/`:
/// `Equal` for a path in that run, without building the prefix. Paths
/// sorted by bytes keep everything below one directory contiguous, but a
/// sibling like `directory.txt` sorts between `directory` and its run.
pub(crate) fn cmp_to_children(path: &str, directory: &str) -> Ordering {
    let path = path.as_bytes();
    let directory = directory.as_bytes();
    let common = path.len().min(directory.len());
    match path[..common].cmp(&directory[..common]) {
        Ordering::Equal => {}
        unequal => return unequal,
    }
    match path.get(directory.len()) {
        // `path` is `directory` itself or a prefix of it.
        None => Ordering::Less,
        Some(&byte) => match byte.cmp(&b'/') {
            Ordering::Equal => Ordering::Equal,
            other => other,
        },
    }
}

