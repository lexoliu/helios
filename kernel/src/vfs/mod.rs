/// Why a mount or unmount was refused.
#[derive(Clone, Debug, Error, PartialEq, Eq)]
pub enum MountError {
    #[error("mount point {0:?} is not a normalized absolute path below /")]
    InvalidPoint(String),
    #[error("{0:?} is already a mount point")]
    AlreadyMounted(String),
    #[error("{0:?} is not a mount point")]
    NotMounted(String),
    #[error("{0:?} is in use: a mount below it, or a descriptor or stream open on it")]
    Busy(String),
    #[error("the mount table holds {MAX_MOUNTS} mounts already")]
    TableFull,
    #[error("the root mount is the kernel's and cannot be mounted again")]
    RootKind,
    #[error("mount point {point:?} cannot be used: {error}")]
    Filesystem { point: String, error: FsError },
}

const SLOT_EMPTY: u8 = 0;
const SLOT_LIVE: u8 = 1;
const SLOT_RETIRING: u8 = 2;

struct Mount<H> {
    point: String,
    rights: FileSystemRights,
    fs: MountedFs<H>,
    /// The table's own share of the mount's hold; any other share is a
    /// descriptor or stream that keeps the mount from being unmounted.
    hold: MountHold,
}

/// What an open descriptor or file stream keeps of the mount it resolved
/// through: while any is alive, [`MountTable::unmount`] refuses with
/// [`MountError::Busy`], as POSIX `umount` refuses a filesystem with
/// files open on it. Clones share one hold.
///
/// It is a count and nothing else, so a descriptor carries it without
/// naming the filesystem's type.
#[derive(Clone)]
pub struct MountHold(Arc<()>);

impl MountHold {
    fn new() -> Self {
        Self(Arc::new(()))
    }

    /// Whether anything besides the table holds the mount.
    fn is_held(&self) -> bool {
        !self.0.is_unique()
    }
}

impl core::fmt::Debug for MountHold {
    fn fmt(&self, formatter: &mut core::fmt::Formatter<'_>) -> core::fmt::Result {
        formatter.write_str("MountHold")
    }
}

/// What a resolution found in one table: the mount that owns a path,
/// pinned for as long as the resolution looks at it.
struct Located<'a, H> {
    point_len: usize,
    mount: &'a Mount<H>,
    pin: SlotPin<'a>,
}

/// One mount's place in the table.
///
/// `point_len` and `point_hash` summarise the mount point for a resolution
/// that scans the table without pinning anything: the writer sets them
/// only while the slot is empty, before it publishes the slot live, and a
/// resolution confirms its candidate against the mount itself once it has
/// pinned the slot. `mount` is written only by the writer, only while
/// `state` is [`SLOT_EMPTY`] or [`SLOT_RETIRING`] with no pins, and read
/// only by a resolution that pinned the slot and then saw [`SLOT_LIVE`].
struct Slot<H> {
    state: AtomicU8,
    point_len: AtomicUsize,
    point_hash: AtomicU64,
    mount: UnsafeCell<Option<Mount<H>>>,
}

// SAFETY: `mount` is shared across processors under the protocol on
// `Slot`: the writer touches it only when no resolution can be reading it
// (empty, or retiring with no pins), and a resolution reads it only after
// pinning the slot and observing it live, which the writer's sequentially
// consistent publication orders after the write.
unsafe impl<H: Send + Sync> Sync for Slot<H> {}

impl<H> Slot<H> {
    fn new() -> Self {
        Self {
            state: AtomicU8::new(SLOT_EMPTY),
            point_len: AtomicUsize::new(0),
            point_hash: AtomicU64::new(0),
            mount: UnsafeCell::new(None),
        }
    }
}

/// 64-bit FNV-1a over a mount point: what a scan compares instead of the
/// point, which it may not read before it pins the slot. The offset basis
/// and prime are FNV's published 64-bit parameters.
fn point_hash(point: &[u8]) -> u64 {
    point.iter().fold(0xcbf2_9ce4_8422_2325, |hash, &byte| {
        (hash ^ u64::from(byte)).wrapping_mul(0x0000_0100_0000_01b3)
    })
}

/// How many resolutions look at each slot of a table, counted per
/// processor.
///
/// A resolution adds one to the count its processor keeps for the slot
/// it uses and takes one away from the count of the processor it finishes
/// on. Each processor's counts share one padded block that only that
/// processor writes, except once by a task that moved between the two
/// writes. The counts wrap, and a slot's pins are their wrapping sum.
///
/// The sum an unmount reads after marking the slot retiring is zero only
/// when no pin is live, although it reads the processors one at a time: a
/// pin taken before the slot retired is counted where it was taken, which
/// the unmount reads after retiring it; a pin taken after sees the slot
/// retiring and undoes itself on the same processor in the same call
/// ([`TableInner::pin_live`]), so no pin's release is ever counted
/// without its taking, and no pin counts below zero.
struct Pins {
    blocks: Box<[CachePadded<[AtomicUsize; MAX_MOUNTS]>]>,
}

impl Pins {
    fn new(processors: usize) -> Self {
        Self {
            blocks: (0..processors)
                .map(|_| CachePadded::new(core::array::from_fn(|_| AtomicUsize::new(0))))
                .collect(),
        }
    }

    /// The executing processor's count for `slot`.
    fn local(&self, slot: usize) -> &AtomicUsize {
        let processor = usize::from(current_processor().id());
        let block = self.blocks.get(processor).unwrap_or_else(|| {
            panic!(
                "processor {processor} resolves a path but the mount table counts {} processors",
                self.blocks.len()
            )
        });
        &block[slot]
    }

    /// The pins on `slot`, summed over every processor.
    fn total(&self, slot: usize) -> usize {
        self.blocks.iter().fold(0, |sum, block| {
            sum.wrapping_add(block[slot].load(AtomicOrdering::SeqCst))
        })
    }
}

/// A resolution's pin on one slot: while it lives, an unmount of the slot
/// waits.
struct SlotPin<'a> {
    pins: &'a Pins,
    slot: usize,
}

impl<'a> SlotPin<'a> {
    fn new(pins: &'a Pins, slot: usize) -> Self {
        pins.local(slot).fetch_add(1, AtomicOrdering::SeqCst);
        Self { pins, slot }
    }
}

impl Drop for SlotPin<'_> {
    fn drop(&mut self) {
        self.pins
            .local(self.slot)
            .fetch_sub(1, AtomicOrdering::Release);
    }
}

/// An unmount's hold on a slot it marked retiring.
///
/// [`Retiring::retire`] empties the slot once nothing pins it. Dropped
/// without that, because the unmount was cancelled while it waited for
/// resolutions to let go, the guard puts the slot back to live: the mount
/// is still in place, and a retiring slot that nothing will ever empty
/// would hide it from every resolution and refuse every later unmount.
struct Retiring<'a, H> {
    table: &'a TableInner<H>,
    index: usize,
}

impl<H> Retiring<'_, H> {
    fn slot(&self) -> &Slot<H> {
        &self.table.slots[self.index]
    }

    /// Whether a descriptor or stream holds the retiring mount.
    fn held(&self) -> bool {
        // SAFETY: the slot is retiring and its mount stays in place until
        // this guard empties it; only the hold's count is read.
        unsafe { &*self.slot().mount.get() }
            .as_ref()
            .expect("a retiring slot holds a mount")
            .hold
            .is_held()
    }

    /// Takes the mount out of the slot and leaves the slot empty.
    fn retire(self) -> Option<Mount<H>> {
        let this = core::mem::ManuallyDrop::new(self);
        let _writer = this.table.writer.lock();
        // SAFETY: the slot is retiring with no pins and the writer lock is
        // held; every resolution that pins it from here on sees it
        // retiring and leaves the mount alone.
        let retired = unsafe { (*this.slot().mount.get()).take() };
        this.slot().state.store(SLOT_EMPTY, AtomicOrdering::Release);
        retired
    }
}

impl<H> Drop for Retiring<'_, H> {
    fn drop(&mut self) {
        let _writer = self.table.writer.lock();
        self.slot().state.store(SLOT_LIVE, AtomicOrdering::SeqCst);
    }
}

/// What every mount table of one kernel shares: the boot image under each
/// namespace's root, and the device numbers mounted trees are given, which
/// must stay distinct however many tables there are.
struct Machine {
    boot: BootFs,
    next_device: AtomicU64,
    /// Processors that may resolve a path: one pin block each, in every
    /// table.
    processors: usize,
}

struct TableInner<H> {
    machine: Arc<Machine>,
    slots: [Slot<H>; MAX_MOUNTS],
    pins: Pins,
    writer: spin::Mutex<()>,
}

// A resolution remembers the slots it has ruled out in one `u32`.
const _: () = assert!(MAX_MOUNTS <= u32::BITS as usize);

impl<H> TableInner<H> {
    /// Pins slot `index` and answers its mount while the slot is live.
    ///
    /// The pin is taken and, when the slot turns out not to be live,
    /// released in this one synchronous call, so a pin that backs off
    /// never moves to another processor: [`Pins`] relies on it.
    fn pin_live(&self, index: usize) -> Option<(&Mount<H>, SlotPin<'_>)> {
        let slot = &self.slots[index];
        if slot.state.load(AtomicOrdering::Acquire) != SLOT_LIVE {
            return None;
        }
        let pin = SlotPin::new(&self.pins, index);
        if slot.state.load(AtomicOrdering::SeqCst) != SLOT_LIVE {
            return None;
        }
        // SAFETY: the slot is pinned and live, so the writer has published
        // the mount and will not touch it until this pin is released (see
        // `Slot`); the reference goes out only beside the pin.
        let mount = unsafe { &*slot.mount.get() }
            .as_ref()
            .expect("a live slot holds a mount");
        Some((mount, pin))
    }

    /// Runs `read` on the mount in slot `index` when it is live, with the
    /// slot pinned for the duration.
    fn read<R>(&self, index: usize, read: impl FnOnce(&Mount<H>) -> R) -> Option<R> {
        self.pin_live(index).map(|(mount, _pin)| read(mount))
    }

    /// The live mount whose point is the longest prefix of `absolute`,
    /// among those longer than `longer_than`.
    ///
    /// The scan reads each slot's published point length and hash and
    /// pins nothing; only the winner is pinned, and confirmed against its
    /// mount under the pin. A winner that does not confirm (a hash that
    /// collided, or a slot unmounted and filled again since the scan) is
    /// ruled out and the scan runs again, so each mount is seen whole,
    /// before or after a concurrent change to it.
    fn longest_match(&self, absolute: &str, longer_than: usize) -> Option<Located<'_, H>> {
        let mut ruled_out = 0u32;
        loop {
            let mut best: Option<(usize, usize)> = None;
            for (index, slot) in self.slots.iter().enumerate() {
                if ruled_out & (1 << index) != 0
                    || slot.state.load(AtomicOrdering::Acquire) != SLOT_LIVE
                {
                    continue;
                }
                let len = slot.point_len.load(AtomicOrdering::Relaxed);
                if len <= best.map_or(longer_than, |(_, best)| best) {
                    continue;
                }
                if prefix_is_point(absolute, len, slot.point_hash.load(AtomicOrdering::Relaxed)) {
                    best = Some((index, len));
                }
            }
            let (index, point_len) = best?;
            if let Some((mount, pin)) = self.pin_live(index)
                && mount.point.len() == point_len
                && point_covers(&mount.point, absolute)
            {
                return Some(Located {
                    point_len,
                    mount,
                    pin,
                });
            }
            ruled_out |= 1 << index;
        }
    }
}

/// Whether the first `len` bytes of `absolute` end at a path boundary and
/// hash to `hash`: a scan's guess that a mount point of that length and
/// hash covers `absolute`.
fn prefix_is_point(absolute: &str, len: usize, hash: u64) -> bool {
    let bytes = absolute.as_bytes();
    match bytes.get(len) {
        None if bytes.len() == len => {}
        Some(b'/') => {}
        _ => return false,
    }
    point_hash(&bytes[..len]) == hash
}

/// One namespace's own mounts. Clones share it.
pub struct MountTable<H> {
    inner: Arc<TableInner<H>>,
}

impl<H> Clone for MountTable<H> {
    fn clone(&self) -> Self {
        Self {
            inner: self.inner.clone(),
        }
    }
}

/// Whether `absolute` is `point` or lies below it.
fn point_covers(point: &str, absolute: &str) -> bool {
    absolute
        .strip_prefix(point)
        .is_some_and(|rest| rest.is_empty() || rest.starts_with('/'))
}

/// A mount point: a normalized absolute path other than `/`.
fn valid_point(point: &str) -> bool {
    point.len() > 1 && point.strip_prefix('/').and_then(FsPath::new).is_some()
}

impl<H: Clone> MountTable<H> {
    /// A kernel's first table: `boot` under each namespace's own layer,
    /// with nothing mounted, for a machine of `processors` processors.
    pub fn new(boot: BootFs, processors: usize) -> Self {
        Self::on(Arc::new(Machine {
            boot,
            next_device: AtomicU64::new(AuthorityDomain::FIRST_MOUNTED.raw()),
            processors,
        }))
    }

    fn on(machine: Arc<Machine>) -> Self {
        let pins = Pins::new(machine.processors);
        Self {
            inner: Arc::new(TableInner {
                machine,
                slots: core::array::from_fn(|_| Slot::new()),
                pins,
                writer: spin::Mutex::new(()),
            }),
        }
    }

    /// An empty table on the same kernel, for a namespace that descends
    /// from this one's.
    fn descendant(&self) -> Self {
        Self::on(self.inner.machine.clone())
    }

    /// The boot image under every namespace's root.
    pub fn boot(&self) -> &BootFs {
        &self.inner.machine.boot
    }

    /// A device id no other filesystem on this kernel has, for a tree the
    /// table is about to mount.
    pub fn allocate_device(&self) -> DeviceId {
        DeviceId::new(
            self.inner
                .machine
                .next_device
                .fetch_add(1, AtomicOrdering::Relaxed),
        )
    }

    /// Mounts `fs` at `point`.
    ///
    /// Checks only the table: the namespace that asks checks the point
    /// against the filesystem beneath it first (see [`Namespace::mount`]).
    pub fn mount(
        &self,
        point: &str,
        fs: MountedFs<H>,
        rights: FileSystemRights,
    ) -> Result<(), MountError> {
        if !valid_point(point) {
            return Err(MountError::InvalidPoint(point.to_owned()));
        }
        if matches!(fs, MountedFs::Root(_)) {
            return Err(MountError::RootKind);
        }
        let _writer = self.inner.writer.lock();
        let mut empty = None;
        for slot in &self.inner.slots {
            match slot.state.load(AtomicOrdering::Acquire) {
                SLOT_EMPTY => {
                    empty.get_or_insert(slot);
                }
                _ => {
                    // SAFETY: the writer lock is held, so no other writer
                    // is changing this slot, and a live or retiring slot's
                    // mount stays in place until a writer clears it.
                    let mounted = unsafe { &*slot.mount.get() };
                    if mounted.as_ref().is_some_and(|mount| mount.point == point) {
                        return Err(MountError::AlreadyMounted(point.to_owned()));
                    }
                }
            }
        }
        let slot = empty.ok_or(MountError::TableFull)?;
        // SAFETY: the slot is empty and the writer lock is held: no
        // resolution reads an empty slot's mount and no writer races.
        unsafe {
            *slot.mount.get() = Some(Mount {
                point: point.to_owned(),
                rights,
                fs,
                hold: MountHold::new(),
            });
        }
        slot.point_len.store(point.len(), AtomicOrdering::Relaxed);
        slot.point_hash
            .store(point_hash(point.as_bytes()), AtomicOrdering::Relaxed);
        slot.state.store(SLOT_LIVE, AtomicOrdering::SeqCst);
        Ok(())
    }

    /// Unmounts the filesystem at `point`, once no resolution is looking
    /// at it.
    ///
    /// A mount with a mount below it, or with a descriptor or stream still
    /// holding it ([`MountHold`]), is in use: [`MountError::Busy`], and the
    /// mount stays as it was.
    pub async fn unmount(&self, point: &str) -> Result<(), MountError> {
        let busy = || MountError::Busy(point.to_owned());
        let index = {
            let _writer = self.inner.writer.lock();
            let mut found = None;
            for (index, slot) in self.inner.slots.iter().enumerate() {
                if slot.state.load(AtomicOrdering::Acquire) != SLOT_LIVE {
                    continue;
                }
                // SAFETY: as in `mount`, the writer lock is held.
                let mounted = unsafe { &*slot.mount.get() }
                    .as_ref()
                    .expect("a live slot holds a mount");
                if mounted.point == point {
                    if mounted.hold.is_held() {
                        return Err(busy());
                    }
                    found = Some(index);
                } else if point_covers(point, &mounted.point) {
                    return Err(busy());
                }
            }
            let index = found.ok_or_else(|| MountError::NotMounted(point.to_owned()))?;
            self.inner.slots[index]
                .state
                .store(SLOT_RETIRING, AtomicOrdering::SeqCst);
            index
        };
        // From here the slot is retiring; whatever ends this call, the
        // guard leaves it live or empty, never retiring.
        let retiring = Retiring {
            table: &self.inner,
            index,
        };
        while self.inner.pins.total(index) != 0 {
            crate::yield_now().await;
        }
        // Every resolution that could have taken a share has let go, and
        // none can take one now: a share still out is a holder.
        if retiring.held() {
            return Err(busy());
        }
        drop(retiring.retire());
        Ok(())
    }

    /// Whether a mount point lies strictly below `directory`.
    fn points_below(&self, directory: &str) -> bool {
        (0..MAX_MOUNTS).any(|index| {
            self.inner.read(index, |mount| {
                mount.point != directory && within_directory(directory, &mount.point)
            }) == Some(true)
        })
    }

    /// Names of the mount points directly inside the directory
    /// `directory`.
    fn points_inside(&self, directory: &str) -> Vec<String> {
        let mut names = Vec::new();
        for index in 0..MAX_MOUNTS {
            if let Some(Some(name)) = self.inner.read(index, |mount| {
                let (parent, name) = mount.point.rsplit_once('/')?;
                let parent = if parent.is_empty() { "/" } else { parent };
                (parent == directory).then(|| String::from(name))
            }) {
                names.push(name);
            }
        }
        names
    }
}

/// A guest path resolved to the mount that owns it.
///
/// It borrows the mount from the table, and the path from the caller
/// unless a symbolic link was followed: a resolution copies nothing and
/// writes no line another processor writes. While it lives, the slot it
/// resolved through stays pinned, so an unmount of that mount waits for
/// it. An operation that outlives its caller's borrow (a stream across
/// polls) keeps a [`HeldPath`] instead.
pub struct Resolved<'a, H> {
    fs: &'a MountedFs<H>,
    rights: FileSystemRights,
    absolute: Cow<'a, str>,
    /// Length of the mount point in `absolute`; `0` for the root mount.
    point_len: usize,
    /// The mount's hold; `None` for the namespace's root, which is never
    /// unmounted.
    hold: Option<&'a MountHold>,
    /// The pin on the mount's slot; `None` for the root, and for a view
    /// of a [`HeldPath`], which owns what it uses.
    _pin: Option<SlotPin<'a>>,
}

impl<'a, H: HostFileSystem> Resolved<'a, H> {
    /// The filesystem, for reading.
    pub fn fs(&self) -> &'a MountedFs<H> {
        self.fs
    }

    /// The filesystem, for changing: refused when the mount is read-only.
    pub fn writable(&self) -> FsResult<&'a MountedFs<H>> {
        if self.rights.contains(FileSystemRights::WRITE) {
            Ok(self.fs)
        } else {
            Err(FsError::ReadOnly)
        }
    }

    /// The path inside the mount's filesystem.
    pub fn path(&self) -> FsPath<'_> {
        let inside = &self.absolute[self.point_len..];
        FsPath::new(inside.strip_prefix('/').unwrap_or(inside))
            .expect("a resolved path is normalized")
    }

    /// The guest path this was resolved from.
    pub fn absolute(&self) -> &str {
        &self.absolute
    }

    /// The guest path of the mount's root.
    pub fn mount_point(&self) -> &str {
        if self.point_len == 0 {
            "/"
        } else {
            &self.absolute[..self.point_len]
        }
    }

    /// Whether `other` lies on the same mount, so a rename or link between
    /// the two can stay within one filesystem.
    pub fn same_mount(&self, other: &Resolved<'_, H>) -> bool {
        self.mount_point() == other.mount_point()
    }

    /// A share of the hold on the mount this resolved through, for a
    /// descriptor or stream that keeps using it; `None` on the namespace's
    /// root, which is never unmounted.
    pub fn hold(&self) -> Option<MountHold> {
        self.hold.cloned()
    }

    /// Whether the path names the root of its mount.
    pub fn is_mount_root(&self) -> bool {
        self.path().is_root()
    }

    /// An owned copy of this resolution, for an operation that keeps
    /// using the file after the caller's borrow ends. It holds the mount
    /// ([`MountHold`]) rather than pinning its slot.
    pub fn held(&self) -> HeldPath<H> {
        HeldPath(Arc::new(HeldInner {
            fs: self.fs.clone(),
            rights: self.rights,
            absolute: String::from(&*self.absolute),
            point_len: self.point_len,
            hold: self.hold(),
        }))
    }

    /// The whole of the regular file at this path, with the provenance of
    /// the layer that produced the bytes.
    pub async fn read_whole(&self) -> FsResult<FileContents> {
        let path = self.path();
        match self.fs {
            MountedFs::Root(root) => root.read_whole(path).await,
            MountedFs::Boot(boot) => boot.file_contents(path).map(FileContents::Boot),
            MountedFs::Memory(fs) => read_all(fs, path).await.map(FileContents::Written),
            MountedFs::Host(fs) => read_all(fs, path).await.map(FileContents::Written),
        }
    }
}

/// A resolution a stream keeps across polls: it owns the filesystem
/// handle and the path, and holds the mount, so an unmount refuses with
/// [`MountError::Busy`] until it is dropped. Clones share one copy.
pub struct HeldPath<H>(Arc<HeldInner<H>>);

struct HeldInner<H> {
    fs: MountedFs<H>,
    rights: FileSystemRights,
    absolute: String,
    point_len: usize,
    hold: Option<MountHold>,
}

impl<H> Clone for HeldPath<H> {
    fn clone(&self) -> Self {
        Self(self.0.clone())
    }
}

impl<H: HostFileSystem> HeldPath<H> {
    /// The resolution this keeps, to operate through.
    pub fn resolved(&self) -> Resolved<'_, H> {
        let held = &*self.0;
        Resolved {
            fs: &held.fs,
            rights: held.rights,
            absolute: Cow::Borrowed(&held.absolute),
            point_len: held.point_len,
            hold: held.hold.as_ref(),
            _pin: None,
        }
    }
}

/// A file's whole contents, typed by the layer that produced them.
///
/// Provenance is decided by which filesystem returned the bytes, in the
/// same call that returned them, never by a path or a separate check a
/// concurrent change could invalidate. Only the boot image constructs
/// [`FileContents::Boot`]; every other layer (a namespace's own tree, a
/// tree in kernel memory, a host share, bytes copied up from the boot
/// image) yields [`FileContents::Written`].
#[derive(Clone, Debug)]
pub enum FileContents {
    /// Bytes exactly as the boot payload supplied them.
    Boot(BootfsBytes),
    /// Bytes any other filesystem holds.
    Written(Bytes),
}

/// The whole of the regular file at `path` on `fs`.
pub(crate) async fn read_all<F: FileSystem>(fs: &F, path: FsPath<'_>) -> FsResult<Bytes> {
    let metadata = fs.stat(path).await?;
    match metadata.kind {
        NodeKind::File => {}
        NodeKind::Directory => return Err(FsError::IsDirectory),
        NodeKind::Symlink => return Err(FsError::Invalid),
    }
    let size = usize::try_from(metadata.size).map_err(|_| FsError::Overflow)?;
    let first = fs.read_at(path, 0, size).await?;
    if first.len() == size {
        return Ok(first);
    }
    // A filesystem may answer in pieces (9p bounds one read by its
    // message size): gather the rest.
    let mut gathered = BytesMut::with_capacity(size);
    gathered.extend_from_slice(&first);
    loop {
        let chunk = fs
            .read_at(path, gathered.len() as u64, size - gathered.len())
            .await?;
        if chunk.is_empty() {
            break;
        }
        gathered.extend_from_slice(&chunk);
    }
    Ok(gathered.freeze())
}

/// The kernel's identity for a filesystem object.
pub fn object_identity(metadata: &Metadata) -> ObjectIdentity {
    ObjectIdentity::new(
        AuthorityDomain::new(metadata.id.device.raw()),
        metadata.id.inode,
    )
}

/// One process tree's view of the filesystem.
///
/// A namespace is a tree of processes: the processes that share one are
/// one tree (a clone is the same tree), and [`Namespace::descend`] starts a
/// new tree below it. Each tree has its own root layer over the boot image
/// and its own [`MountTable`]. A mount belongs to the tree that made it:
/// that tree and every tree descending from it see it, no other tree does,
/// and only the tree that made it unmounts it. The kernel's own mounts (the
/// host share at `/host`) belong to the root namespace, from which every
/// program's tree descends.
///
/// Resolution reads this tree's table and then each ancestor's, nearest
/// first, with no lock: the chain of ancestors is fixed when the tree
/// starts, and each table resolves lock-free.
pub struct Namespace<H> {
    /// This tree's own mounts.
    own: MountTable<H>,
    /// The tables of the trees this one descends from, nearest first.
    inherited: Arc<Vec<MountTable<H>>>,
    /// The writable layer of the root.
    layer: MemoryFs,
    /// The root: `layer` over the boot image, as the filesystem a
    /// resolution that no mount claims borrows.
    root: MountedFs<H>,
}

impl<H: Clone> Clone for Namespace<H> {
    fn clone(&self) -> Self {
        Self {
            own: self.own.clone(),
            inherited: self.inherited.clone(),
            layer: self.layer.clone(),
            root: self.root.clone(),
        }
    }
}

impl<H: Clone> Namespace<H> {
    /// The root namespace, over `table`: the kernel's own tree, with a
    /// fresh root layer and no ancestors.
    pub fn new(table: MountTable<H>) -> Self {
        Self::over(
            table,
            Arc::new(Vec::new()),
            MemoryFs::new(ROOT_LAYER_DEVICE),
        )
    }

    fn over(own: MountTable<H>, inherited: Arc<Vec<MountTable<H>>>, layer: MemoryFs) -> Self {
        let root = MountedFs::Root(RootFs::new(layer.clone(), own.boot().clone()));
        Self {
            own,
            inherited,
            layer,
            root,
        }
    }

    /// A new tree descending from this one: a fresh root layer and an
    /// empty table of its own, seeing every mount this tree sees.
    pub fn descend(&self) -> Self {
        let inherited = core::iter::once(self.own.clone())
            .chain(self.inherited.iter().cloned())
            .collect();
        Self::over(
            self.own.descendant(),
            Arc::new(inherited),
            MemoryFs::new(ROOT_LAYER_DEVICE),
        )
    }

    /// Whether `other` is the same tree: shares this one's mounts and root.
    pub fn same_tree(&self, other: &Self) -> bool {
        Arc::ptr_eq(&self.own.inner, &other.own.inner)
    }

    /// The writable layer of this tree's root, which a child that ran to
    /// completion hands back to the parent it rejoins.
    pub fn root_layer(&self) -> MemoryFs {
        self.layer.clone()
    }

    /// Takes `layer` as this tree's root layer: the one a child that ran
    /// to completion hands back. The tree's mounts stay as they are.
    pub fn adopt_root_layer(&mut self, layer: MemoryFs) {
        self.root = MountedFs::Root(RootFs::new(layer.clone(), self.own.boot().clone()));
        self.layer = layer;
    }

    /// This tree's own mounts.
    pub fn table(&self) -> &MountTable<H> {
        &self.own
    }

    /// Every table this tree sees, its own first.
    fn tables(&self) -> impl Iterator<Item = &MountTable<H>> {
        core::iter::once(&self.own).chain(self.inherited.iter())
    }
}

impl<H: HostFileSystem> Namespace<H> {
    /// Resolves a normalized absolute guest path (as
    /// [`crate::resolve_child_path`] produces) to the mount that owns it.
    ///
    /// The longest mount point wins; between two at the same point, the
    /// nearer tree's, so a tree may mount over what it inherited.
    pub fn resolve<'a>(&'a self, absolute: &'a str) -> FsResult<Resolved<'a, H>> {
        self.resolve_path(Cow::Borrowed(absolute))
    }

    fn resolve_path<'a>(&'a self, absolute: Cow<'a, str>) -> FsResult<Resolved<'a, H>> {
        if !absolute.starts_with('/') {
            return Err(FsError::Invalid);
        }
        // Nearest table first, and a farther one only for a strictly
        // longer point: the nearer tree wins a tie.
        let mut found: Option<Located<'a, H>> = None;
        for table in self.tables() {
            let longer_than = found.as_ref().map_or(0, |best| best.point_len);
            if let Some(located) = table.inner.longest_match(&absolute, longer_than) {
                found = Some(located);
            }
        }
        let resolved = match found {
            Some(Located {
                point_len,
                mount,
                pin,
            }) => Resolved {
                fs: &mount.fs,
                rights: mount.rights,
                absolute,
                point_len,
                hold: Some(&mount.hold),
                _pin: Some(pin),
            },
            None => Resolved {
                fs: &self.root,
                rights: FileSystemRights::READ | FileSystemRights::WRITE,
                absolute,
                point_len: 0,
                hold: None,
                _pin: None,
            },
        };
        let inside = &resolved.absolute[resolved.point_len..];
        FsPath::new(inside.strip_prefix('/').unwrap_or(inside)).ok_or(FsError::Invalid)?;
        Ok(resolved)
    }

    /// Resolves `absolute`, following a final symbolic link as `follow`
    /// says, through as many mounts as the links lead to.
    ///
    /// A followed resolution starts inside its floor and never leaves it:
    /// a link that leads out, a link placed at the floor itself included,
    /// is refused with [`FsError::NotPermitted`].
    pub async fn resolve_following<'a>(
        &'a self,
        absolute: &'a str,
        follow: Follow<'_>,
    ) -> FsResult<Resolved<'a, H>> {
        let mut resolved = self.resolve(absolute)?;
        let Follow::Within(floor) = follow else {
            return Ok(resolved);
        };
        if !within_directory(floor, absolute) {
            return Err(FsError::NotPermitted);
        }
        for _ in 0..MAX_SYMLINK_DEPTH {
            match resolved.fs().stat(resolved.path()).await {
                Ok(metadata) if metadata.kind == NodeKind::Symlink => {}
                // Absent, or not a link: the path names itself.
                Ok(_) | Err(FsError::NoEntry) => return Ok(resolved),
                Err(error) => return Err(error),
            }
            let target = resolved.fs().read_link(resolved.path()).await?;
            let followed = symlink_target(resolved.absolute(), &target)?;
            if !within_directory(floor, &followed) {
                return Err(FsError::NotPermitted);
            }
            resolved = self.resolve_path(Cow::Owned(followed))?;
        }
        Err(FsError::Loop)
    }

    /// Describes `absolute`, following a final symbolic link as `follow`
    /// says.
    pub async fn stat(&self, absolute: &str, follow: Follow<'_>) -> FsResult<Metadata> {
        let resolved = self.resolve_following(absolute, follow).await?;
        resolved.fs().stat(resolved.path()).await
    }

    /// Every entry of the directory at `absolute`, with the mount points
    /// directly inside it, which the filesystem beneath may not have.
    pub async fn list(&self, absolute: &str) -> FsResult<Vec<DirEntry>> {
        /// Entries one listing request asks for.
        const BATCH: usize = 256;
        let resolved = self.resolve(absolute)?;
        let mut entries: Vec<DirEntry> = Vec::new();
        let mut cookie = DirCookie::START;
        loop {
            let batch = resolved
                .fs()
                .read_dir(resolved.path(), cookie, BATCH)
                .await?;
            let complete = batch.len() < BATCH;
            if let Some(last) = batch.last() {
                cookie = last.next;
            }
            entries.extend(batch);
            if complete {
                break;
            }
        }
        for name in self
            .tables()
            .flat_map(|table| table.points_inside(absolute))
        {
            if !entries.iter().any(|entry| entry.name == name) {
                entries.push(DirEntry {
                    name,
                    kind: NodeKind::Directory,
                    inode: 0,
                    next: DirCookie::START,
                });
            }
        }
        Ok(entries)
    }

    /// Whether a mount point lies strictly below `absolute`.
    fn holds_mounts(&self, absolute: &str) -> bool {
        self.tables().any(|table| table.points_below(absolute))
    }

    /// Removes the empty directory `absolute`. A mount point, or a
    /// directory with a mount point below it, is in use:
    /// [`FsError::Busy`].
    pub async fn remove_directory(&self, absolute: &str, payer: &StoragePayer) -> FsResult<()> {
        let resolved = self.resolve(absolute)?;
        if resolved.is_mount_root() || self.holds_mounts(absolute) {
            return Err(FsError::Busy);
        }
        resolved
            .writable()?
            .remove_directory(resolved.path(), payer)
            .await
    }

    /// Renames within one mount; across two, [`FsError::CrossDevice`]. A
    /// directory with a mount point below it stays where it is:
    /// [`FsError::Busy`].
    pub async fn rename(
        &self,
        source: &str,
        destination: &str,
        now: u64,
        payer: &StoragePayer,
    ) -> FsResult<()> {
        if self.holds_mounts(source) {
            return Err(FsError::Busy);
        }
        let source = self.resolve(source)?;
        let destination = self.resolve(destination)?;
        if source.is_mount_root() || destination.is_mount_root() {
            return Err(FsError::Busy);
        }
        if !source.same_mount(&destination) {
            return Err(FsError::CrossDevice);
        }
        source
            .writable()?
            .rename(source.path(), destination.path(), now, payer)
            .await
    }

    /// Links within one mount; across two, [`FsError::CrossDevice`].
    pub async fn link(
        &self,
        existing: &str,
        link: &str,
        now: u64,
        payer: &StoragePayer,
    ) -> FsResult<()> {
        let existing = self.resolve(existing)?;
        let link = self.resolve(link)?;
        if !existing.same_mount(&link) {
            return Err(FsError::CrossDevice);
        }
        if existing.is_mount_root() || link.is_mount_root() {
            return Err(FsError::NotPermitted);
        }
        existing
            .writable()?
            .link(existing.path(), link.path(), now, payer)
            .await
    }

    /// Mounts `fs` at the point `cap` names, after checking the point
    /// against what lies beneath it: its parent must be a directory, and
    /// the point itself a directory or nothing.
    pub async fn mount(
        &self,
        cap: &MountCap,
        fs: MountedFs<H>,
        rights: FileSystemRights,
    ) -> Result<(), MountError> {
        let point = cap.point();
        if !valid_point(point) {
            return Err(MountError::InvalidPoint(point.to_owned()));
        }
        let refuse = |error| MountError::Filesystem {
            point: point.to_owned(),
            error,
        };
        let parent = crate::parent_path(point);
        // The cap is the authority over where a mount goes, so the parent's
        // links are followed anywhere in the namespace.
        match self
            .stat(parent, Follow::Within("/"))
            .await
            .map_err(refuse)?
            .kind
        {
            NodeKind::Directory => {}
            NodeKind::File | NodeKind::Symlink => return Err(refuse(FsError::NotDirectory)),
        }
        match self.stat(point, Follow::No).await {
            Ok(metadata) if metadata.kind != NodeKind::Directory => {
                return Err(refuse(FsError::NotDirectory));
            }
            Ok(_) | Err(FsError::NoEntry) => {}
            Err(error) => return Err(refuse(error)),
        }
        self.own.mount(point, fs, rights)
    }

    /// Unmounts the filesystem this tree mounted at the point `cap` names,
    /// once no resolution is looking at it. A mount an ancestor made is
    /// not this tree's to remove: [`MountError::NotMounted`]. A descriptor
    /// or stream any tree holds on the mount keeps it busy.
    pub async fn unmount(&self, cap: &UnmountCap) -> Result<(), MountError> {
        self.own.unmount(cap.point()).await
    }
}

/// Whether a resolution follows a final symbolic link.
#[derive(Clone, Copy, Debug)]
pub enum Follow<'a> {
    /// The path names the link itself.
    No,
    /// The path names what the link leads to, which must lie inside the
    /// directory given: the descriptor or grant the path was resolved
    /// against.
    Within(&'a str),
}

/// Whether `path` is the directory `directory` or lies below it.
pub fn within_directory(directory: &str, path: &str) -> bool {
    directory == "/" && path.starts_with('/') || point_covers(directory, path)
}

/// The guest path a symbolic link at `link` with target text `target`
/// names.
///
/// Targets stay inside the directory that holds the link: an absolute
/// target or one that climbs with `..` is refused, as the guest
/// filesystem has always refused them.
pub fn symlink_target(link: &str, target: &str) -> FsResult<String> {
    if target.is_empty() || target.starts_with('/') {
        return Err(FsError::NotPermitted);
    }
    if target.split('/').any(|segment| segment == "..") {
        return Err(FsError::NotPermitted);
    }
    crate::resolve_child_path(crate::parent_path(link), target).map_err(|_| FsError::NotPermitted)
}

/// `directory/name` as a filesystem-relative path.
pub(crate) fn join_fs_path(directory: FsPath<'_>, name: &str) -> String {
    if directory.is_root() {
        return name.to_owned();
    }
    let mut joined = String::with_capacity(directory.as_str().len() + 1 + name.len());
    joined.push_str(directory.as_str());
    joined.push('/');
    joined.push_str(name);
    joined
}

/// Orders `path` against the run of paths that start with `directory/`:
/// `Equal` for a path in that run, without building the prefix. Paths
/// sorted by bytes keep everything below one directory contiguous, but a
/// sibling like `directory.txt` sorts between `directory` and its run.
pub(crate) fn cmp_to_children(path: &str, directory: &str) -> Ordering {
    let path = path.as_bytes();
    let directory = directory.as_bytes();
    let common = path.len().min(directory.len());
    match path[..common].cmp(&directory[..common]) {
        Ordering::Equal => {}
        unequal => return unequal,
    }
    match path.get(directory.len()) {
        // `path` is `directory` itself or a prefix of it.
        None => Ordering::Less,
        Some(&byte) => match byte.cmp(&b'/') {
            Ordering::Equal => Ordering::Equal,
            other => other,
        },
    }
}

