/// Maximum Ethernet frame payload including the Ethernet header and FCS-free
/// frame bytes used by virtio-net and common Ethernet NICs.
pub const ETHERNET_FRAME_BYTES: usize = 1514;
/// Conservative default poll budget for single-queue virtio-style devices.
pub const DEFAULT_POLL_BUDGET: usize = 8;

/// Hardware checksum offload capabilities exposed by a NIC.
#[derive(Clone, Copy, Debug, Default, PartialEq, Eq)]
pub struct ChecksumOffload {
    /// IPv4 header checksum can be validated by hardware on receive.
    pub rx_ipv4: bool,
    /// TCP checksum can be validated by hardware on receive.
    pub rx_tcp: bool,
    /// UDP checksum can be validated by hardware on receive.
    pub rx_udp: bool,
    /// IPv4 header checksum can be generated by hardware on transmit.
    pub tx_ipv4: bool,
    /// TCP checksum can be generated by hardware on transmit.
    pub tx_tcp: bool,
    /// UDP checksum can be generated by hardware on transmit.
    pub tx_udp: bool,
}

/// Hardware segmentation and coalescing capabilities.
#[derive(Clone, Copy, Debug, Default, PartialEq, Eq)]
pub struct SegmentationOffload {
    /// TCP segmentation offload for IPv4 packets.
    pub tx_tcp_ipv4: bool,
    /// TCP large receive offload for IPv4 packets.
    pub rx_tcp_ipv4: bool,
    /// Maximum payload bytes accepted by TSO.
    pub max_tx_segment_bytes: usize,
}

/// Multi-queue and flow steering capabilities.
#[derive(Clone, Copy, Debug, Default, PartialEq, Eq)]
pub struct QueueTopology {
    /// Number of receive queues available to the stack.
    pub rx_queues: usize,
    /// Number of transmit queues available to the stack.
    pub tx_queues: usize,
    /// Receive-side scaling hash can steer flows across receive queues.
    pub rss: bool,
}

/// Event delivery and moderation capabilities for avoiding interrupt storms.
#[derive(Clone, Copy, Debug, Default, PartialEq, Eq)]
pub struct EventDeliveryCapabilities {
    /// Device progress can be polled without waiting for an interrupt.
    pub polling: bool,
    /// Device can notify progress through interrupts.
    pub interrupts: bool,
    /// Device or driver can adapt interrupt moderation to load.
    pub adaptive_moderation: bool,
    /// Receive interrupts can be coalesced.
    pub rx_coalescing: bool,
    /// Transmit-completion interrupts can be coalesced.
    pub tx_coalescing: bool,
    /// Preferred maximum receive frames to drain before yielding.
    pub rx_poll_budget: usize,
    /// Preferred maximum transmit completions to drain before yielding.
    pub tx_completion_budget: usize,
}

/// Hardware capabilities that let the stack specialize hot paths.
#[derive(Clone, Copy, Debug, Default, PartialEq, Eq)]
pub struct InterfaceCapabilities {
    /// Maximum FCS-free frame bytes the interface accepts.
    pub max_frame_len: usize,
    /// Supported checksum offloads.
    pub checksum: ChecksumOffload,
    /// Supported segmentation and coalescing offloads.
    pub segmentation: SegmentationOffload,
    /// Queue topology visible to the stack.
    pub queues: QueueTopology,
    /// Event delivery and moderation capabilities.
    pub events: EventDeliveryCapabilities,
    /// DMA can read borrowed packet bytes directly when that path wins.
    pub direct_tx_dma: bool,
    /// DMA can fill stack-owned packet buffers directly when that path wins.
    pub direct_rx_dma: bool,
}

